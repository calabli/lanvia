import "C"

import (
	"errors"
	"strings"
	"sync"
	"unsafe"
)

var (
	pbMu      sync.Mutex
	pbCount   C.long = -1
	pbLastTxt string
)

func clipboardSupported() bool { return true }

// useTestPasteboard 让本进程改用一个独立的剪贴板（只在测试里调用），不影响用户的系统剪贴板。
func useTestPasteboard() bool {
	C.lanviaUseTestPasteboard()
	pbMu.Lock()
	pbCount = -1
	pbMu.Unlock()
	return true
}

func readClipboard() (string, error) {
	pbMu.Lock()
	defer pbMu.Unlock()
	n := C.lanviaChangeCount()
	if n == pbCount {
		return pbLastTxt, nil
	}
	pbCount = n
	p := C.lanviaReadText()
	if p == nil {
		pbLastTxt = ""
		return "", nil
	}
	defer C.free(unsafe.Pointer(p))
	pbLastTxt = C.GoString(p)
	return pbLastTxt, nil
}

func writeClipboard(s string) error {
	cs := C.CString(s)
	defer C.free(unsafe.Pointer(cs))
	if C.lanviaWriteText(cs) == 0 {
		return errors.New("写入剪贴板失败")
	}
	return nil
}

func skipClipboardChange() bool { return C.lanviaShouldSkip() == 1 }

// clipSeq 是剪贴板的变化计数，内容每变一次加一。不支持时返回 -1。
func clipSeq() int64 { return int64(C.lanviaChangeCount()) }

func readClipboardImage() ([]byte, error) {
	var n C.long
	p := C.lanviaReadImage(&n)
	if p == nil {
		return nil, errNoImage
	}
	defer C.free(p)
	return C.GoBytes(p, C.int(n)), nil
}

func writeClipboardImage(data []byte) error {
	if len(data) == 0 {
		return errNoImage
	}
	p := C.CBytes(data)
	defer C.free(p)
	if C.lanviaWriteImage(p, C.long(len(data))) == 0 {
		return errors.New("写入剪贴板失败")
	}
	return nil
}

func frontApp() (id, name string) {
	p := C.lanviaFrontApp()
	if p == nil {
		return "", ""
	}
	defer C.free(unsafe.Pointer(p))
	id, name, _ = strings.Cut(C.GoString(p), "\n")
	return id, name
}
