import "C"

import (
	"errors"
	"sync"
	"unsafe"
)

var (
	pbMu      sync.Mutex
	pbCount   C.long = -1
	pbLastTxt string
)

func clipboardSupported() bool { return true }

func readClipboard() (string, error) {
	pbMu.Lock()
	defer pbMu.Unlock()
	n := C.lanviaChangeCount()
	if n == pbCount {
		return pbLastTxt, nil
	}
	pbCount = n
	p := C.lanviaReadText()
	if p == nil {
		pbLastTxt = ""
		return "", nil
	}
	defer C.free(unsafe.Pointer(p))
	pbLastTxt = C.GoString(p)
	return pbLastTxt, nil
}

func writeClipboard(s string) error {
	cs := C.CString(s)
	defer C.free(unsafe.Pointer(cs))
	if C.lanviaWriteText(cs) == 0 {
		return errors.New("写入剪贴板失败")
	}
	return nil
}

func skipClipboardChange() bool { return C.lanviaShouldSkip() == 1 }
